// Helper function to get driver image path
export const getDriverImage = (name) => {
    // Check if we have a direct mapping
    if (driverImages[name]) {
        return driverImages[name];
    }

    // Convert name to filename format (replace spaces with underscores, handle special chars)
    const filename = name
        .replace(/ /g, '_')
        .replace(/é/g, 'e')
        .replace(/ö/g, 'o')
        .replace(/ü/g, 'u')
        .replace(/á/g, 'a')
        .replace(/í/g, 'i')
        .replace(/ó/g, 'o')
        .replace(/ñ/g, 'n')
        .replace(/-/g, '');
    return `/plots/${filename}.png`;
};

// Get driver by name from any list
export const getDriverByName = (name) => {
    const allDrivers = [...allTimePeakElo, ...currentGrid2025];
    return allDrivers.find(d => d.name.toLowerCase() === name.toLowerCase());
};
